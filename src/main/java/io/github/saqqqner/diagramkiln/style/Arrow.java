package io.github.saqqqner.diagramkiln.style;

/**
 * Arrowhead choices for the source or target of a connection.
 */
public enum Arrow {
  /**
   * No arrowhead.
   */
  NONE,
  /**
   * A notched triangular arrowhead.
   */
  CLASSIC,
  /**
   * A filled triangular arrowhead.
   */
  BLOCK,
  /**
   * An open arrowhead.
   */
  OPEN,
  /**
   * A diamond arrowhead.
   */
  DIAMOND
}
